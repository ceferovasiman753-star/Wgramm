/** Тянет карту из колоды; если колода пуста — тасует заново из source (как draw_card в Python). */
function drawCard(deck, source) {
  if (!deck.length) {
    deck.push(...source);
    for (let i = deck.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [deck[i], deck[j]] = [deck[j], deck[i]];
    }
  }
  return deck.pop();
}

