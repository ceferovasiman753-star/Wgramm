/** true, если автор — владелец бота или админ чата; иначе сама отправляет отказ и возвращает false. */
async function requireAdmin(api, lang, message) {
  if (isOwner(message.from)) return true;
  if (message.chat.type === "private") {
    await api.sendMessage(message.chat.id, t(lang, "group_only"));
    return false;
  }
  if (!(await isAdmin(api, message.chat.id, message.from.id))) {
    await api.sendMessage(message.chat.id, t(lang, "admins_only"));
    return false;
  }
  return true;
}

/** Назначать/снимать админов может только создатель ЭТОЙ группы или владелец бота. */
async function requireCreatorOrOwner(api, lang, message) {
  if (message.chat.type === "private") {
    await api.sendMessage(message.chat.id, t(lang, "group_only"));
    return false;
  }
  if (isOwner(message.from)) return true;
  if (await isCreator(api, message.chat.id, message.from.id)) return true;
  await api.sendMessage(message.chat.id, t(lang, "creator_or_owner_only"));
  return false;
}

