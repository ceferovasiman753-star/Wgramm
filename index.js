// telegram.js — тонкая обёртка над Telegram Bot API через fetch().
// В Cloudflare Workers нет aiogram/Bot, поэтому все методы дергаются напрямую по HTTP.

const API_ROOT = "https://api.telegram.org";

/**
 * Низкоуровневый вызов метода Telegram Bot API.
 * Бросает Error с текстом ошибки Telegram, если ok:false — вызывающий код это ловит
 * так же, как ловил aiogram.exceptions.TelegramBadRequest в Python-версии.
 */
async function callTelegram(token, method, payload) {
  const res = await fetch(`${API_ROOT}/bot${token}/${method}`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(payload || {}),
  });
  const data = await res.json();
  if (!data.ok) {
    const err = new Error(data.description || `Telegram API error in ${method}`);
    err.telegram = data;
    throw err;
  }
  return data.result;
}

function makeApi(token) {
  return {
    sendMessage: (chatId, text, extra = {}) =>
      callTelegram(token, "sendMessage", {
        chat_id: chatId,
        text,
        parse_mode: "HTML",
        ...extra,
      }),

    answerCallbackQuery: (callbackQueryId, extra = {}) =>
      callTelegram(token, "answerCallbackQuery", {
        callback_query_id: callbackQueryId,
        ...extra,
      }),

    deleteMessage: (chatId, messageId) =>
      callTelegram(token, "deleteMessage", { chat_id: chatId, message_id: messageId }),

    banChatMember: (chatId, userId) =>
      callTelegram(token, "banChatMember", { chat_id: chatId, user_id: userId }),

    unbanChatMember: (chatId, userId, extra = {}) =>
      callTelegram(token, "unbanChatMember", { chat_id: chatId, user_id: userId, ...extra }),

    restrictChatMember: (chatId, userId, permissions, untilDate) =>
      callTelegram(token, "restrictChatMember", {
        chat_id: chatId,
        user_id: userId,
        permissions,
        ...(untilDate ? { until_date: Math.floor(untilDate.getTime() / 1000) } : {}),
      }),

    promoteChatMember: (chatId, userId, rights) =>
      callTelegram(token, "promoteChatMember", { chat_id: chatId, user_id: userId, ...rights }),

    getChatMember: (chatId, userId) =>
      callTelegram(token, "getChatMember", { chat_id: chatId, user_id: userId }),

    getChatAdministrators: (chatId) =>
      callTelegram(token, "getChatAdministrators", { chat_id: chatId }),

    setWebhook: (url) => callTelegram(token, "setWebhook", { url, allowed_updates: ["message", "callback_query", "chat_member"] }),
  };
}

