async function handleMessage(api, env, message) {
  const chatId = message.chat.id;
  const lang = await getLang(env, chatId);
  const parsed = parseCommand(message.text || "");
  if (!parsed) return;
  const { cmd, args } = parsed;

  switch (cmd) {
    case "start":
      await api.sendMessage(
        chatId,
        t(lang, "start_text", { truths: TRUTHS.length, dares: DARES.length }),
        { reply_markup: mainMenuKb(lang) }
      );
      return;

    case "language":
      await api.sendMessage(chatId, t(lang, "language_prompt"), { reply_markup: languageKb() });
      return;

    case "add": {
      const room = await getRoom(env, chatId);
      const name = args;
      if (!name) {
        await api.sendMessage(chatId, t(lang, "add_need_name"));
        return;
      }
      if (room.players.includes(name)) {
        await api.sendMessage(chatId, t(lang, "add_already", { name }));
        return;
      }
      room.players.push(name);
      await saveRoom(env, chatId, room);
      await api.sendMessage(chatId, t(lang, "add_added", { name, count: room.players.length }), {
        reply_markup: mainMenuKb(lang),
      });
      return;
    }

    case "remove": {
      const room = await getRoom(env, chatId);
      const name = args;
      if (room.players.includes(name)) {
        room.players = room.players.filter((p) => p !== name);
        await saveRoom(env, chatId, room);
        await api.sendMessage(chatId, t(lang, "remove_removed", { name }));
      } else {
        await api.sendMessage(chatId, t(lang, "remove_notfound", { name }));
      }
      return;
    }

    case "players":
      await sendPlayersList(api, env, chatId, lang);
      return;

    case "reset":
      await resetRoom(env, chatId);
      await api.sendMessage(chatId, t(lang, "reset_done"));
      return;

    case "target": {
      if (!isOwner(message.from)) {
        await api.sendMessage(chatId, t(lang, "owner_only"));
        return;
      }
      const room = await getRoom(env, chatId);
      const name = args;
      if (!name) {
        const playersStr = room.players.length ? room.players.join(", ") : t(lang, "target_empty_list");
        await api.sendMessage(chatId, t(lang, "target_need_name", { players: playersStr }));
        return;
      }
      if (!room.players.includes(name)) {
        await api.sendMessage(chatId, t(lang, "target_notfound", { name }));
        return;
      }
      room.current_player = name;
      await saveRoom(env, chatId, room);
      await api.sendMessage(chatId, t(lang, "spin_turn", { name }), { reply_markup: truthDareKb(lang) });
      return;
    }

    // ---------- модерация ----------

    case "ban": {
      if (!(await requireAdmin(api, lang, message))) return;
      const target = getReplyTarget(message);
      if (!target) {
        await api.sendMessage(chatId, t(lang, "reply_needed_ban"));
        return;
      }
      const reason = parseReason(args);
      try {
        await api.banChatMember(chatId, target.id);
        let text = t(lang, "ban_done", { name: fullName(target) });
        if (reason) text += "\n" + t(lang, "reason_label", { reason });
        await api.sendMessage(chatId, text);
      } catch (e) {
        await api.sendMessage(chatId, t(lang, "ban_fail", { err: e.message }));
      }
      return;
    }

    case "unban": {
      if (!(await requireAdmin(api, lang, message))) return;
      const target = getReplyTarget(message);
      if (!target) {
        await api.sendMessage(chatId, t(lang, "reply_needed_unban"));
        return;
      }
      try {
        await api.unbanChatMember(chatId, target.id);
        await api.sendMessage(chatId, t(lang, "unban_done", { name: fullName(target) }));
      } catch (e) {
        await api.sendMessage(chatId, t(lang, "unban_fail", { err: e.message }));
      }
      return;
    }

    case "kick": {
      if (!(await requireAdmin(api, lang, message))) return;
      const target = getReplyTarget(message);
      if (!target) {
        await api.sendMessage(chatId, t(lang, "reply_needed_kick"));
        return;
      }
      try {
        await api.banChatMember(chatId, target.id);
        await api.unbanChatMember(chatId, target.id); // бан+разбан = кик (может зайти обратно)
        await api.sendMessage(chatId, t(lang, "kick_done", { name: fullName(target) }));
      } catch (e) {
        await api.sendMessage(chatId, t(lang, "kick_fail", { err: e.message }));
      }
      return;
    }

    case "mute": {
      if (!(await requireAdmin(api, lang, message))) return;
      const target = getReplyTarget(message);
      if (!target) {
        await api.sendMessage(chatId, t(lang, "reply_needed_mute"));
        return;
      }
      let untilDate = null;
      let reason = "";
      if (args) {
        const spaceIdx = args.indexOf(" ");
        const first = spaceIdx === -1 ? args : args.slice(0, spaceIdx);
        const rest = spaceIdx === -1 ? "" : args.slice(spaceIdx + 1).trim();
        const durMs = parseDurationMs(first);
        if (durMs) {
          untilDate = new Date(Date.now() + durMs);
          reason = rest;
        } else {
          reason = args;
        }
      }
      try {
        await api.restrictChatMember(chatId, target.id, { can_send_messages: false }, untilDate);
        let text = untilDate
          ? t(lang, "mute_done_until", { name: fullName(target), until: formatUntil(untilDate) })
          : t(lang, "mute_done_forever", { name: fullName(target) });
        if (reason) text += "\n" + t(lang, "reason_label", { reason });
        await api.sendMessage(chatId, text);
      } catch (e) {
        await api.sendMessage(chatId, t(lang, "mute_fail", { err: e.message }));
      }
      return;
    }

    case "unmute": {
      if (!(await requireAdmin(api, lang, message))) return;
      const target = getReplyTarget(message);
      if (!target) {
        await api.sendMessage(chatId, t(lang, "reply_needed_unmute"));
        return;
      }
      try {
        await api.restrictChatMember(chatId, target.id, {
          can_send_messages: true,
          can_send_audios: true,
          can_send_documents: true,
          can_send_photos: true,
          can_send_videos: true,
          can_send_video_notes: true,
          can_send_voice_notes: true,
          can_send_polls: true,
          can_send_other_messages: true,
          can_add_web_page_previews: true,
        });
        await api.sendMessage(chatId, t(lang, "unmute_done", { name: fullName(target) }));
      } catch (e) {
        await api.sendMessage(chatId, t(lang, "unmute_fail", { err: e.message }));
      }
      return;
    }

    // ---------- варны ----------

    case "warn": {
      if (!(await requireAdmin(api, lang, message))) return;
      const target = getReplyTarget(message);
      if (!target) {
        await api.sendMessage(chatId, t(lang, "reply_needed_warn"));
        return;
      }
      const settings = await getSettings(env, chatId);
      const reason = parseReason(args);
      const count = (settings.warns[target.id] || 0) + 1;
      settings.warns[target.id] = count;
      const maxWarns = settings.max_warns;

      let text = t(lang, "warn_given", { name: fullName(target), count, max: maxWarns });
      if (reason) text += "\n" + t(lang, "reason_label", { reason });

      if (count >= maxWarns) {
        try {
          await api.banChatMember(chatId, target.id);
          settings.warns[target.id] = 0;
          text += t(lang, "warn_limit_ban", { name: fullName(target) });
        } catch (e) {
          text += t(lang, "warn_limit_ban_fail", { err: e.message });
        }
      }
      await saveSettings(env, chatId, settings);
      await api.sendMessage(chatId, text);
      return;
    }

    case "warns": {
      const settings = await getSettings(env, chatId);
      const target = getReplyTarget(message) || message.from;
      const count = settings.warns[target.id] || 0;
      await api.sendMessage(
        chatId,
        t(lang, "warns_count", { name: fullName(target), count, max: settings.max_warns })
      );
      return;
    }

    case "resetwarns": {
      if (!(await requireAdmin(api, lang, message))) return;
      const target = getReplyTarget(message);
      if (!target) {
        await api.sendMessage(chatId, t(lang, "reply_needed_generic"));
        return;
      }
      const settings = await getSettings(env, chatId);
      settings.warns[target.id] = 0;
      await saveSettings(env, chatId, settings);
      await api.sendMessage(chatId, t(lang, "resetwarns_done", { name: fullName(target) }));
      return;
    }

    // ---------- purge ----------

    case "purge": {
      if (!(await requireAdmin(api, lang, message))) return;
      if (!message.reply_to_message) {
        await api.sendMessage(chatId, t(lang, "purge_need_reply"));
        return;
      }
      const startId = message.reply_to_message.message_id;
      const endId = message.message_id;
      let deleted = 0;
      for (let msgId = startId; msgId <= endId; msgId++) {
        try {
          await api.deleteMessage(chatId, msgId);
          deleted++;
        } catch {
          // сообщение уже удалено / недоступно для удаления — пропускаем
        }
      }
      const note = await api.sendMessage(chatId, t(lang, "purge_done", { count: deleted }));
      // "Note" исчезает через 3 секунды, как в оригинале.
      // setTimeout недоступен между запросами воркера, поэтому просто пробуем сразу же
      // с небольшой паузой — Workers допускают await внутри одного вызова.
      await new Promise((resolve) => setTimeout(resolve, 3000));
      try {
        await api.deleteMessage(chatId, note.message_id);
      } catch {
        // сообщение уже удалено — ничего страшного
      }
      return;
    }

    // ---------- приветствие / правила ----------

    case "setwelcome": {
      if (!(await requireAdmin(api, lang, message))) return;
      if (!args) {
        await api.sendMessage(chatId, t(lang, "setwelcome_need_text"));
        return;
      }
      const settings = await getSettings(env, chatId);
      settings.welcome_text = args;
      await saveSettings(env, chatId, settings);
      await api.sendMessage(chatId, t(lang, "setwelcome_saved"));
      return;
    }

    case "setrules": {
      if (!(await requireAdmin(api, lang, message))) return;
      if (!args) {
        await api.sendMessage(chatId, t(lang, "setrules_need_text"));
        return;
      }
      const settings = await getSettings(env, chatId);
      settings.rules_text = args;
      await saveSettings(env, chatId, settings);
      await api.sendMessage(chatId, t(lang, "setrules_saved"));
      return;
    }

    case "rules": {
      const settings = await getSettings(env, chatId);
      if (settings.rules_text) {
        await api.sendMessage(chatId, t(lang, "rules_header", { text: settings.rules_text }));
      } else {
        await api.sendMessage(chatId, t(lang, "rules_empty"));
      }
      return;
    }

    case "admins": {
      if (message.chat.type === "private") {
        await api.sendMessage(chatId, t(lang, "group_only"));
        return;
      }
      const admins = await api.getChatAdministrators(chatId);
      const lines = admins.map((a) => {
        const role = a.status === ChatMemberStatus.CREATOR ? t(lang, "role_creator") : t(lang, "role_admin");
        return `${role} — ${fullName(a.user)}`;
      });
      await api.sendMessage(chatId, t(lang, "admins_header") + "\n" + lines.join("\n"));
      return;
    }

    // ---------- owner-only: promote / demote / owners ----------

    case "promote": {
      if (!(await requireCreatorOrOwner(api, lang, message))) return;
      const target = getReplyTarget(message);
      if (!target) {
        await api.sendMessage(chatId, t(lang, "reply_needed_promote"));
        return;
      }
      try {
        await api.promoteChatMember(chatId, target.id, {
          can_delete_messages: true,
          can_restrict_members: true,
          can_invite_users: true,
          can_pin_messages: true,
          can_manage_chat: true,
          can_change_info: false,
          can_promote_members: false,
        });
        await api.sendMessage(chatId, t(lang, "promote_done", { name: fullName(target) }));
      } catch (e) {
        await api.sendMessage(chatId, t(lang, "promote_fail", { err: e.message }));
      }
      return;
    }

    case "demote": {
      if (!(await requireCreatorOrOwner(api, lang, message))) return;
      const target = getReplyTarget(message);
      if (!target) {
        await api.sendMessage(chatId, t(lang, "reply_needed_demote"));
        return;
      }
      try {
        await api.promoteChatMember(chatId, target.id, {
          can_delete_messages: false,
          can_restrict_members: false,
          can_invite_users: false,
          can_pin_messages: false,
          can_manage_chat: false,
          can_change_info: false,
          can_promote_members: false,
        });
        await api.sendMessage(chatId, t(lang, "demote_done", { name: fullName(target) }));
      } catch (e) {
        await api.sendMessage(chatId, t(lang, "demote_fail", { err: e.message }));
      }
      return;
    }

    case "owners":
      await api.sendMessage(chatId, t(lang, "owners_text"));
      return;

    case "help":
      await api.sendMessage(chatId, t(lang, "help_text"));
      return;

    default:
      return; // неизвестная команда — молча игнорируем, как и оригинальный бот
  }
}

// ======================================================================
//  ОБРАБОТКА CALLBACK-КНОПОК
// ======================================================================

async function handleCallback(api, env, callback) {
  const chatId = callback.message.chat.id;
  const lang = await getLang(env, chatId);
  const data = callback.data || "";

  if (data.startsWith("lang_")) {
    const langCode = data.replace("lang_", "");
    await setLang(env, chatId, langCode, LANGUAGES);
    await api.sendMessage(chatId, t(langCode, "language_set"));
    await api.answerCallbackQuery(callback.id);
    return;
  }

  switch (data) {
    case "list_players":
      await sendPlayersList(api, env, chatId, lang);
      await api.answerCallbackQuery(callback.id);
      return;

    case "spin": {
      const room = await getRoom(env, chatId);
      if (room.players.length < 2) {
        await api.answerCallbackQuery(callback.id, { text: t(lang, "spin_need_players"), show_alert: true });
        return;
      }
      const chosen = room.players[Math.floor(Math.random() * room.players.length)];
      room.current_player = chosen;
      await saveRoom(env, chatId, room);
      await api.sendMessage(chatId, t(lang, "spin_turn", { name: chosen }), {
        reply_markup: truthDareKb(lang),
      });
      await api.answerCallbackQuery(callback.id);
      return;
    }

    case "truth": {
      const room = await getRoom(env, chatId);
      const player = room.current_player || "Player";
      const question = drawCard(room.truth_deck, TRUTHS);
      await saveRoom(env, chatId, room);
      await api.sendMessage(chatId, t(lang, "truth_header", { name: player, text: question }), {
        reply_markup: afterCardKb(lang),
      });
      await api.answerCallbackQuery(callback.id);
      return;
    }

    case "dare": {
      const room = await getRoom(env, chatId);
      const player = room.current_player || "Player";
      const action = drawCard(room.dare_deck, DARES);
      await saveRoom(env, chatId, room);
      await api.sendMessage(chatId, t(lang, "dare_header", { name: player, text: action }), {
        reply_markup: afterCardKb(lang),
      });
      await api.answerCallbackQuery(callback.id);
      return;
    }

    default:
      await api.answerCallbackQuery(callback.id);
      return;
  }
}

// ======================================================================
//  ПРИВЕТСТВИЕ новых участников (апдейт типа chat_member)
// ======================================================================

async function handleChatMemberUpdate(api, env, event) {
  const oldStatus = event.old_chat_member.status;
  const newStatus = event.new_chat_member.status;
  const joined =
    (oldStatus === ChatMemberStatus.LEFT || oldStatus === ChatMemberStatus.KICKED) &&
    newStatus === ChatMemberStatus.MEMBER;
  if (!joined) return;

  const chatId = event.chat.id;
  const lang = await getLang(env, chatId);
  const settings = await getSettings(env, chatId);
  const name = fullName(event.new_chat_member.user);

  const text = settings.welcome_text
    ? settings.welcome_text.replace(/\{name\}/g, name)
    : t(lang, "welcome_default", { name });

  await api.sendMessage(chatId, text);
}
