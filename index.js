/**
 * Форматирует шаблон текста, аналог Python str.format(**kwargs).
 * Если kwargs не передан (или пуст) — строка возвращается как есть,
 * включая литеральные "{{name}}" в некоторых текстах (так было и в оригинале).
 */
function formatTemplate(template, kwargs) {
  if (!kwargs || Object.keys(kwargs).length === 0) return template;
  return template.replace(/\{(\w+)\}/g, (match, key) =>
    Object.prototype.hasOwnProperty.call(kwargs, key) ? String(kwargs[key]) : match
  );
}

/**
 * t(lang, key, kwargs) — получить переведённый и отформатированный текст.
 * В отличие от Python-версии, язык передаётся явно (уже прочитанный из KV),
 * а не берётся из глобального словаря по chat_id.
 */
function t(lang, key, kwargs) {
  const entry = TEXTS[key] || {};
  const template = entry[lang] || entry[DEFAULT_LANG] || key;
  return formatTemplate(template, kwargs);
}

