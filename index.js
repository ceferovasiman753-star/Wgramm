// ---------------------------------------------------------------------------
// worker.js — точка входа Cloudflare Worker.
// Заменяет aiogram + long polling (bot_main.py) на Telegram webhook.
//
// Как это работает:
//   Telegram -> POST https://<твой-воркер>.workers.dev/  -> fetch() ниже
//   Мы отвечаем 200 сразу же и обрабатываем апдейт в фоне через ctx.waitUntil,
//   чтобы Telegram не считал вебхук медленным и не слал повторы.
//
// Настройка (см. README.md для подробностей):
//   1. Secret:      BOT_TOKEN = токен от @BotFather
//   2. Переменная:  WEBHOOK_SECRET (необязательно, но рекомендуется) — любая строка
//   3. KV binding:  BOT_KV — namespace для состояния игр/варнов/языка (см. state.js)
//   4. После деплоя вызвать один раз (замени значения):
//      https://api.telegram.org/bot<BOT_TOKEN>/setWebhook?url=https://<worker>.workers.dev&secret_token=<WEBHOOK_SECRET>


// --- Владельцы бота (полный доступ во всех чатах, независимо от статуса админа в группе) ---
const OWNER_USERNAMES = new Set([
  "soltex1k",       // @SOLTEX1K
  "ganjinski_32",   // @GANJINSKI_32
  "asshhirranni",   // @asshhirranni
]);

const DURATION_RE = /^(\d+)([mhd])$/; // 10m / 2h / 1d

export default {
  async fetch(request, env, ctx) {
    if (request.method !== "POST") {
      return new Response("Bot is running.", { status: 200 });
    }

    if (env.WEBHOOK_SECRET) {
      const header = request.headers.get("X-Telegram-Bot-Api-Secret-Token");
      if (header !== env.WEBHOOK_SECRET) {
        return new Response("forbidden", { status: 403 });
      }
    }

    let update;
    try {
      update = await request.json();
    } catch {
      return new Response("bad request", { status: 400 });
    }

    // Отвечаем Telegram сразу, а сам апдейт обрабатываем в фоне.
    ctx.waitUntil(
      handleUpdate(update, env).catch((err) => console.error("handleUpdate error:", err))
    );
    return new Response("ok");
  },
};

async function handleUpdate(update, env) {
  const api = makeApi(env.BOT_TOKEN);
  if (update.message) return handleMessage(api, env, update.message);
  if (update.callback_query) return handleCallback(api, env, update.callback_query);
  if (update.chat_member) return handleChatMemberUpdate(api, env, update.chat_member);
}

// ---------- утилиты ----------

function fullName(user) {
  if (!user) return "";
  return user.last_name ? `${user.first_name} ${user.last_name}` : user.first_name;
}

function parseCommand(text) {
  if (!text || !text.startsWith("/")) return null;
  const spaceIdx = text.indexOf(" ");
  const cmdPart = spaceIdx === -1 ? text : text.slice(0, spaceIdx);
  const args = spaceIdx === -1 ? "" : text.slice(spaceIdx + 1).trim();
  const atIdx = cmdPart.indexOf("@");
  const cmd = (atIdx === -1 ? cmdPart : cmdPart.slice(0, atIdx)).slice(1).toLowerCase();
  return { cmd, args };
}

function parseDurationMs(text) {
  const m = DURATION_RE.exec((text || "").trim());
  if (!m) return null;
  const value = parseInt(m[1], 10);
  const unit = m[2];
  if (unit === "m") return value * 60 * 1000;
  if (unit === "h") return value * 60 * 60 * 1000;
  if (unit === "d") return value * 24 * 60 * 60 * 1000;
  return null;
}

function formatUntil(date) {
  const dd = String(date.getUTCDate()).padStart(2, "0");
  const mm = String(date.getUTCMonth() + 1).padStart(2, "0");
  const HH = String(date.getUTCHours()).padStart(2, "0");
  const MI = String(date.getUTCMinutes()).padStart(2, "0");
  return `${dd}.${mm} ${HH}:${MI}`;
}

/** Аналог parse_reason из Python: убирает из остатка текста ведущий токен-длительность, если он там есть. */
function parseReason(args) {
  if (!args) return "";
  const spaceIdx = args.indexOf(" ");
  const first = spaceIdx === -1 ? args : args.slice(0, spaceIdx);
  const rest = spaceIdx === -1 ? "" : args.slice(spaceIdx + 1).trim();
  if (DURATION_RE.test(first)) return rest;
  return args;
}

function isOwner(from) {
  return Boolean(from && from.username && OWNER_USERNAMES.has(from.username.toLowerCase()));
}

